assert.equal(foam.fixedIce,'少冰');assert.equal(iceChoices(foam,de,'大杯',false).join(','),'少冰');
assert.equal(foam.variants.find(v=>v.size==='大杯').price,60);
assert(!foam.variants.some(v=>v.temp!=='冷'));
