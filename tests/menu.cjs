assert.equal(query({...defaults(),brand:'得正',temp:'熱'}).yes.some(d=>d.id===foam.id),false);
const winter=drinks.find(d=>d.name==='冬瓜拿鐵');assert.equal(winter.fixedSugar,'甜度固定');
