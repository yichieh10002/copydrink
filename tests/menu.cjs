for(const d of drinks){assert(d.source||d.brand==='WUWIN');assert(d.variants.length);assert(d.menuCategory);for(const v of d.variants){assert(Number.isFinite(v.price));assert(v.cal===null||Number.isFinite(v.cal));}}
