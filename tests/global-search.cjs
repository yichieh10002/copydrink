const assert=require('node:assert/strict'),fs=require('node:fs');
const {findMatches}=require('../dist/search-model.js');
const brands=[{name:'得正',aliases:['dejeng']},{name:'WUWIN'}];
const types=[{id:'fresh',label:'鮮奶茶',aliases:['拿鐵','鮮奶']},{id:'tea',label:'純茶'}];
const drinks=[{id:'a',brand:'得正',name:'紅茶鮮奶',menuCategory:'Fresh MILK',type:'fresh',note:'Black Tea Latte'}, {id:'b',brand:'WUWIN',name:'黑糖拿鐵',menuCategory:'拿鐵',type:'fresh'},{id:'c',brand:'得正',name:'紅茶',menuCategory:'Original TEA',type:'tea'}];
const search=q=>findMatches({brands,drinks,types,q});
assert.equal(search('').items.length,2);assert(search('').items.every(x=>x.kind==='brand'));
assert.equal(search('ＤＥＪＥＮＧ').items[0].brand,'得正');
assert.equal(search('紅茶').items[0].id,'c','exact product match ranks before prefix matches');
assert.equal(search('紅茶').items[1].id,'a');
assert.equal(search('鮮奶').items.filter(x=>x.kind==='drink').length,2,'type alias finds products across brands without type result rows');
assert.equal(search('latte').items[0].id,'a');
assert.equal(search('<script>alert(1)</script>').total,0);
const many=Array.from({length:120},(_,i)=>({...drinks[0],id:'drink-'+i}));
const capped=findMatches({brands,drinks:many,types,q:'鮮奶',limit:80});assert.equal(capped.total,120);assert.equal(capped.items.length,80);
const html=fs.readFileSync('dist/index.html','utf8');assert(html.includes('id="search-dialog"'));assert(html.includes('id="open-search"'));
for(const id of ['workspace','filter-body','view-compact','view-detail','sort'])assert(!html.includes('id="'+id+'"'),'legacy search workspace removed: '+id);
assert(fs.readFileSync('dist/menu-view.js','utf8').includes("row.id='menu-item-'+d.id"));
console.log('PASS: ranked brand/product/alias search, capped results, direct drink targets and legacy workspace removal');
